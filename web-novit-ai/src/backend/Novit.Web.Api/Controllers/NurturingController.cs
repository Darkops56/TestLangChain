/// <summary>
/// Debug/test endpoints for the nurturing newsletter system.
/// Protected by API key — requires <c>X-Api-Key</c> header.
/// </summary>
[ApiController]
[Route("api/nurturing")]
[RequireApiKey]
public sealed class NurturingController(
    INurturingMailService mailService,
    IPipedriveService pipedrive,
    IAgentClient agentClient,
    IOptions<NurturingOptions> nurturingOptions,
    NovitDbContext db,
    IServiceScopeFactory scopeFactory,
    ILogger<NurturingController> logger) : ControllerBase
{
    // ── Background send status tracking ─────────────────────────────
    private static volatile SendStatus? _activeSend;

    private sealed class SendStatus
    {
        public string MonthKey { get; init; } = "";
        public int Version { get; init; }
        public string Subject { get; init; } = "";
        public int TotalRecipients { get; init; }
        public int AiClosings { get; set; }
        public int TemplateClosings => TotalRecipients - AiClosings;
        public int Sent { get; set; }
        public int Failed { get; set; }
        public bool IsComplete { get; set; }
        public bool MarkedAsSent { get; set; }
        public DateTimeOffset StartedAt { get; init; } = DateTimeOffset.UtcNow;
        public DateTimeOffset? CompletedAt { get; set; }
        public string? Error { get; set; }
    }

    /// <summary>
    /// Triggers newsletter generation with real web search and returns the result as JSON.
    /// No emails are sent — this is purely for previewing the generated content.
    /// When NURTURING_V2_ENABLED, delegates to the Python agent service.
    /// </summary>
    [HttpPost("test-generate")]
    public async Task<IActionResult> TestGenerate(CancellationToken ct)
    {
        logger.LogInformation("Delegating newsletter generation to Python agent");
        var result = await agentClient.GenerateNewsletterAsync(ct);
        if (result is null)
            return StatusCode(502, new { error = "Python agent did not respond or failed to generate newsletter." });

        var fullHtml = NurturingContentRenderer.WrapInHtmlEmail(result.Body);
        return Ok(new
        {
            subject = result.Subject,
            body = result.Body,
            fullHtml,
            reportTitle = result.ReportTitle,
            executiveSummary = result.ExecutiveSummary,
            artifactJson = result.ArtifactJson,
            generatedAt = DateTimeOffset.UtcNow,
            source = "python-agent",
            note = "This is a preview only — no emails were sent. Generated by Python agent."
        });
    }

