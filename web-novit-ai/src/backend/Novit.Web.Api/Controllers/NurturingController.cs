    /// <summary>
    /// Gets newsletter recipients from Pipedrive (nurturing stage).
    /// If RecipientOverride is set AND Pipedrive is not available, falls back to override emails.
    /// The override redirect is applied at send time, not here — so personalization data is preserved.
    /// </summary>
    private async Task<List<PipedriveDealContact>> GetRecipientsAsync(NurturingOptions options, CancellationToken ct)
    {
        if (pipedrive.IsConfigured)
        {
            var contacts = await pipedrive.GetNurturingDealContactsAsync(ct);
            var unique = contacts
                .Where(c => !string.IsNullOrWhiteSpace(c.ContactEmail))
                .GroupBy(c => c.ContactEmail, StringComparer.OrdinalIgnoreCase)
                .Select(g => g.First())
                .ToList();

            if (unique.Count > 0)
                return unique;
        }

        // Fallback: if Pipedrive is not configured or returned empty, use override emails
        if (!string.IsNullOrWhiteSpace(options.RecipientOverride))
        {
            return options.RecipientOverride
                .Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
                .Select(email => new PipedriveDealContact(0, "Override", email, null, null))
                .ToList();
        }

        return [];
    }

    private async Task<(NurturingCycleSlot Cycle, NurturingEmailEntity? Newsletter)?> ResolveNextCycleForDraftAsync(
        DateOnly today,
        CancellationToken ct)
    {
        foreach (var cycle in NurturingSchedule.GetUpcomingCycles(today))
        {
            var existing = await db.NurturingEmails
                .FirstOrDefaultAsync(e => e.MonthKey == cycle.CycleKey, ct);

            if (existing is null || !existing.IsSent)
                return (cycle, existing);
        }

        return null;
    }

    private async Task<(NurturingCycleSlot Cycle, NurturingEmailEntity Newsletter)?> ResolveNextPendingCycleAsync(
        DateOnly today,
        CancellationToken ct)
    {
        foreach (var cycle in NurturingSchedule.GetUpcomingCycles(today))
        {
            var existing = await db.NurturingEmails
                .FirstOrDefaultAsync(e => e.MonthKey == cycle.CycleKey && !e.IsSent, ct);

            if (existing is not null)
                return (cycle, existing);
        }

        return null;
    }

    /// <summary>
    /// Strips Re:, Fwd:, RE:, FW: prefixes (possibly repeated/nested) from an email subject.
    /// </summary>
    private static string StripReplyPrefixes(string subject)
    {
        if (string.IsNullOrWhiteSpace(subject)) return "";
        return System.Text.RegularExpressions.Regex.Replace(
            subject.Trim(), @"^(\s*(Re|Fwd|FW|Fw)\s*:\s*)+", "", System.Text.RegularExpressions.RegexOptions.IgnoreCase).Trim();
    }

    /// <summary>
    /// Checks whether an incoming email's subject matches a newsletter we sent.
    /// Prevents auto-replying to manual conversations with the same contacts.
    /// </summary>
    private static bool IsNurturingNewsletterReply(string emailSubject, IReadOnlyList<string> sentNewsletterSubjects)
    {
        var cleanSubject = StripReplyPrefixes(emailSubject);
        if (string.IsNullOrWhiteSpace(cleanSubject)) return false;

        return sentNewsletterSubjects.Any(ns =>
            cleanSubject.Contains(ns, StringComparison.OrdinalIgnoreCase) ||
            ns.Contains(cleanSubject, StringComparison.OrdinalIgnoreCase));
    }
