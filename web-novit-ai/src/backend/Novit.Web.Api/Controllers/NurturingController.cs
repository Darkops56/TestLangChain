    /// <summary>
    /// Previews the personalized greeting and closing that each Pipedrive contact would receive.
    /// Reads the latest newsletter from the database for subject + body context.
    /// When AI is configured, generates AI-powered closings for contacts with deal history.
    /// Falls back to template-based closings otherwise. No emails are sent.
    /// Optional query parameters:
    /// - <c>?ai=true</c> to enable AI closings (default: template only)
    /// - <c>?dealIds=19&dealIds=20</c> to preview only specific deals
    /// - <c>?limit=10</c> to cap the preview size
    /// </summary>
    [HttpGet("test-personalization")]
    public async Task<IActionResult> TestPersonalization(
        [FromQuery] bool ai = false,
        [FromQuery] int[]? dealIds = null,
        [FromQuery] int? limit = null,
        CancellationToken ct = default)
    {
        if (!pipedrive.IsConfigured)
            return BadRequest(new { error = "Pipedrive is not configured." });

        try
        {
            // Read latest newsletter from DB for subject + body context
            var latestNewsletter = await db.NurturingEmails
                .OrderByDescending(e => e.CreatedAt)
                .FirstOrDefaultAsync(ct);

            var newsletterSubject = latestNewsletter?.Subject ?? "Novedades tech del mes";
            var newsletterBody = latestNewsletter?.Body;

            var contacts = await pipedrive.GetNurturingDealContactsAsync(ct);

            var requestedDealIds = (dealIds ?? [])
                .Where(dealId => dealId > 0)
                .Distinct()
                .ToList();

            if (requestedDealIds.Count > 0)
            {
                var requestedDealIdSet = requestedDealIds.ToHashSet();
                var selected = contacts
                    .Where(c => requestedDealIdSet.Contains(c.DealId))
                    .ToList();

                var foundDealIds = selected
                    .Select(c => c.DealId)
                    .Distinct()
                    .ToHashSet();

                foreach (var missingDealId in requestedDealIds.Where(dealId => !foundDealIds.Contains(dealId)))
                {
                    var directContact = await pipedrive.GetDealContactAsync(missingDealId, ct);
                    if (directContact is not null)
                        selected.Add(directContact);
                }

                contacts = selected;
            }

            // Deduplicate by email
            IEnumerable<PipedriveDealContact> filtered = contacts
                .Where(c => !string.IsNullOrWhiteSpace(c.ContactEmail))
                .GroupBy(c => c.ContactEmail, StringComparer.OrdinalIgnoreCase)
                .Select(g => g.First());

            if (limit.HasValue && limit.Value > 0)
                filtered = filtered.Take(limit.Value);

            var unique = filtered.ToList();

            var useAI = ai && agentClient.IsConfigured;

            var previews = new List<object>();
            foreach (var c in unique)
            {
                var firstName = NurturingWorkflowSupport.ExtractFirstName(c.ContactName);
                var templateClosing = NurturingWorkflowSupport.BuildPersonalClosing(firstName, c.OrganizationName);
                var greeting = string.IsNullOrWhiteSpace(firstName) ? "Hola," : $"Hola {firstName},";

                string? aiClosing = null;
                List<string>? dealContext = null;

                if (useAI)
                {
                    dealContext = await pipedrive.GetDealPersonalizationContextAsync(c.DealId, ct);
                    if (dealContext.Count > 0)
                    {
                        aiClosing = await agentClient.GenerateClosingAsync(
                            newsletterSubject, newsletterBody, firstName, c.OrganizationName, dealContext, ct);
                    }
                }

                previews.Add(new
                {
                    dealId = c.DealId,
                    contactName = c.ContactName,
                    contactEmail = c.ContactEmail,
                    organizationName = c.OrganizationName,
                    firstName,
                    greeting,
                    closingUsed = aiClosing ?? templateClosing,
                    closingSource = aiClosing is not null ? "ai" : "template",
                    templateClosing,
                    aiClosing,
                    dealContextCount = dealContext?.Count,
                    dealContext,
                    dealTitle = c.DealTitle
                });
            }

            var aiCount = previews.Count(p => ((dynamic)p).closingSource == "ai");

            return Ok(new
            {
                totalContacts = previews.Count,
                requestedDealIds = requestedDealIds.Count > 0 ? requestedDealIds : null,
                limitApplied = limit,
                withName = unique.Count(c => c.ContactName is not null),
                withOrg = unique.Count(c => c.OrganizationName is not null),
                aiClosingsGenerated = useAI ? aiCount : (int?)null,
                templateFallbacks = useAI ? previews.Count - aiCount : (int?)null,
                mode = useAI ? "ai+template" : "template-only",
                newsletterSubject,
                newsletterMonthKey = latestNewsletter?.MonthKey,
                previews,
                note = useAI
                    ? "AI closings generated via GPT-4o using newsletter body context. No emails sent."
                    : "Template-only mode. Add ?ai=true to enable AI closings (uses GPT-4o). No emails sent."
            });
        }
        catch (Exception ex)
        {
            logger.LogError(ex, "Failed to preview personalization");
            return StatusCode(500, new { error = "Failed to fetch contacts.", detail = ex.Message });
        }
    }

    /// <summary>
    /// Generates a newsletter and sends it to reviewers for validation, exactly like the
    /// scheduled Monday flow. Saves the newsletter to the database and sends HTML preview
    /// emails to the configured reviewer list.
    /// Delegates generation to the Python agent service.
    /// </summary>
    [HttpPost("trigger-review")]
    public async Task<IActionResult> TriggerReview(CancellationToken ct)
    {
        if (!mailService.IsConfigured)
            return BadRequest(new { error = "Mail service (IMAP/SMTP) is not configured." });

        var options = nurturingOptions.Value;
        var reviewers = options.GetReviewerList();
        if (reviewers.Count == 0)
            return BadRequest(new { error = "No reviewer emails configured (Nurturing:ReviewerEmails)." });

        logger.LogInformation("Delegating trigger-review newsletter generation to Python agent");
        var agentResult = await agentClient.GenerateNewsletterAsync(ct);
        if (agentResult is null)
            return StatusCode(502, new { error = "Python agent did not respond or failed to generate newsletter." });
        var newsletter = agentResult;

        string? slidesUrl = null;
        string? slidesError = null;
        if (!string.IsNullOrWhiteSpace(newsletter.ArtifactJson))
        {
            try
            {
                using var artifactDoc = JsonDocument.Parse(newsletter.ArtifactJson);
                slidesUrl = artifactDoc.RootElement.TryGetProperty("slides_url", out var slidesUrlElement)
                    ? slidesUrlElement.GetString()
                    : null;
                slidesError = artifactDoc.RootElement.TryGetProperty("slides_error", out var slidesErrorElement)
                    ? slidesErrorElement.GetString()
                    : null;
            }
            catch (JsonException ex)
            {
                logger.LogWarning(ex, "Could not parse artifact_json returned by agent during trigger-review");
            }
        }

        try
        {
            var buenosAires = TimeZoneInfo.FindSystemTimeZoneById("America/Buenos_Aires");
            var now = TimeZoneInfo.ConvertTimeFromUtc(DateTime.UtcNow, buenosAires);
            var today = DateOnly.FromDateTime(now);
            var cycleResolution = await ResolveNextCycleForDraftAsync(today, ct);
            if (cycleResolution is null)
                return BadRequest(new { error = "Could not determine the next newsletter cycle." });

            var (cycle, existing) = cycleResolution.Value;
            var monthKey = cycle.CycleKey;

            if (existing is not null)
            {
                // Update existing draft and reset send state so feedback loop works
                existing.Subject = newsletter.Subject;
                existing.Body = newsletter.Body;
                existing.ReportTitle = newsletter.ReportTitle;
                existing.ExecutiveSummary = newsletter.ExecutiveSummary;
                existing.ArtifactJson = newsletter.ArtifactJson;
                existing.Version++;
                existing.IsSent = false;
                existing.IsOnHold = false;
                existing.SentAt = null;
            }
            else
            {
                // Create new entry
                // 11 AM Buenos Aires = 14:00 UTC (UTC-3)
                var scheduledSend = new DateTimeOffset(cycle.SendDate.Year, cycle.SendDate.Month, cycle.SendDate.Day,
                    14, 0, 0, TimeSpan.Zero);

                db.NurturingEmails.Add(new NurturingEmailEntity
                {
                    MonthKey = monthKey,
                    Subject = newsletter.Subject,
                    Body = newsletter.Body,
                    ReportTitle = newsletter.ReportTitle,
                    ExecutiveSummary = newsletter.ExecutiveSummary,
                    ArtifactJson = newsletter.ArtifactJson,
                    ScheduledSendDate = scheduledSend,
                    IsSent = false,
                    Version = 1
                });
            }

            await db.SaveChangesAsync(ct);

            // Send HTML preview to reviewers — the mail itself IS the preview
            var version = existing?.Version ?? 1;
            var reviewSubject = $"[REVISIÓN v{version}] {newsletter.Subject}";

            // Prepend a short reviewer note inside the same email wrapper
            var reviewNote = """
                <p style="background:#fffde7;padding:10px 14px;border-left:3px solid #f9a825;font-size:13px;color:#555;margin-bottom:20px;">
                <b>Nota para revisores:</b> Este es el mail que recibirían los contactos. Respondé con correcciones o comentarios.<br><br>
                <b>⏸ Para suspender el envío</b>, respondé con <b>"NO ENVIAR"</b> y el newsletter quedará en standby hasta nuevo aviso.
                </p>
                """;
            var slidesNote = !string.IsNullOrWhiteSpace(slidesUrl)
                ? $"<p style=\"margin:0 0 18px 0;padding:12px 14px;background:#eef5ff;border:1px solid #c9dcff;border-radius:10px;font-size:13px;color:#1f2430;\"><b>Deck de apoyo:</b> <a href=\"{WebUtility.HtmlEncode(slidesUrl)}\" style=\"color:#0A0089;font-weight:700;\">Abrir Google Slides</a></p>"
                : !string.IsNullOrWhiteSpace(slidesError)
                    ? $"<p style=\"margin:0 0 18px 0;padding:12px 14px;background:#fff4f4;border:1px solid #f3c7c7;border-radius:10px;font-size:13px;color:#7a1f1f;\"><b>Deck no disponible:</b> {WebUtility.HtmlEncode(slidesError)}</p>"
                    : string.Empty;
            var reviewWrapped = NurturingContentRenderer.WrapInHtmlEmail(reviewNote + slidesNote + newsletter.Body);

            await mailService.SendBulkEmailAsync(reviewers, reviewSubject, reviewWrapped, isHtml: true, ct: ct);

            logger.LogInformation("Newsletter v{Version} for {MonthKey} generated and sent to {Count} reviewers",
                version, monthKey, reviewers.Count);

            return Ok(new
            {
                subject = newsletter.Subject,
                bodyHtml = newsletter.Body,
                version,
                monthKey,
                reportTitle = newsletter.ReportTitle,
                executiveSummary = newsletter.ExecutiveSummary,
                artifactJson = newsletter.ArtifactJson,
                slidesUrl,
                slidesError,
                scheduledSendDate = new DateTimeOffset(cycle.SendDate.Year, cycle.SendDate.Month, cycle.SendDate.Day, 14, 0, 0, TimeSpan.Zero),
                reviewersSentTo = reviewers,
                generatedAt = DateTimeOffset.UtcNow,
                note = "Newsletter generated, saved, and sent to reviewers for validation."
            });
        }
        catch (Exception ex)
        {
            logger.LogError(ex, "Trigger-review failed");
            return StatusCode(500, new
            {
                error = "Failed to generate/send newsletter.",
                detail = ex.Message,
                innerDetail = ex.InnerException?.Message
            });
        }
    }

    // ── Manual trigger endpoints ────────────────────────────────────

    /// <summary>
    /// Forces a check for reviewer feedback on the next pending newsletter cycle.
    /// Mirrors the scheduled validation-window flow: detects hold/resume/revision requests,
    /// revises the newsletter with AI if needed, and resends to reviewers.
    /// </summary>
    [HttpPost("trigger-check-feedback")]
    public async Task<IActionResult> TriggerCheckFeedback(CancellationToken ct)
    {
        if (!mailService.IsConfigured)
            return BadRequest(new { error = "Mail service (IMAP/SMTP) is not configured." });

        var options = nurturingOptions.Value;

        logger.LogInformation("Manual trigger-check-feedback requested via endpoint");

        try
        {
            var buenosAires = TimeZoneInfo.FindSystemTimeZoneById("America/Buenos_Aires");
            var now = TimeZoneInfo.ConvertTimeFromUtc(DateTime.UtcNow, buenosAires);
            var today = DateOnly.FromDateTime(now);
            var cycleResolution = await ResolveNextPendingCycleAsync(today, ct);
            if (cycleResolution is null)
                return NotFound(new { error = "No pending newsletter cycle found." });

            var (cycle, newsletter) = cycleResolution.Value;
            var monthKey = cycle.CycleKey;

            if (newsletter is null)
                return NotFound(new { error = $"No unsent newsletter found for {monthKey}." });

            // Fetch replies from reviewers
            var reviewers = options.GetReviewerList();
            var reviewerSet = new HashSet<string>(reviewers, StringComparer.OrdinalIgnoreCase);
            var unanswered = await mailService.GetUnansweredRepliesAsync(7, ct);

            var feedbackEmails = unanswered
                .Where(e => reviewerSet.Contains(e.From) &&
                            e.Subject.Contains("REVISIÓN", StringComparison.OrdinalIgnoreCase))
                .ToList();

            if (feedbackEmails.Count == 0)
                return Ok(new
                {
                    monthKey,
                    version = newsletter.Version,
                    isOnHold = newsletter.IsOnHold,
                    feedbackFound = 0,
                    action = "none",
                    note = "No reviewer feedback found. Newsletter unchanged."
                });

            // Classify feedback
            var holdEmails = feedbackEmails.Where(e => NurturingWorkflowSupport.IsHoldRequest(e.Body)).ToList();
            var resumeEmails = feedbackEmails.Where(e => NurturingWorkflowSupport.IsResumeRequest(e.Body)).ToList();
            var revisionEmails = feedbackEmails.Except(holdEmails).Except(resumeEmails).ToList();

            // Process hold
            if (holdEmails.Count > 0)
            {
                newsletter.IsOnHold = true;
                await db.SaveChangesAsync(ct);

                var holdWrapped = NurturingContentRenderer.WrapInHtmlEmail(
                    "<p style=\"background:#ffebee;padding:10px 14px;border-left:3px solid #e53935;font-size:13px;color:#555;margin-bottom:20px;\"><b>⏸ Newsletter en standby</b><br>" +
                    $"Solicitado por: {string.Join(", ", holdEmails.Select(e => e.From))}<br>" +
                    "Respondé con <b>\"REANUDAR\"</b> o <b>\"ENVIAR\"</b> para retomar el envío.</p>" + newsletter.Body);
                await mailService.SendBulkEmailAsync(reviewers, $"[⏸ EN ESPERA] {newsletter.Subject}", holdWrapped, isHtml: true, ct: ct);

                return Ok(new { monthKey, version = newsletter.Version, action = "hold", holdRequestsFrom = holdEmails.Select(e => e.From) });
            }

            // Process resume
            if (resumeEmails.Count > 0 && newsletter.IsOnHold)
            {
                newsletter.IsOnHold = false;
                await db.SaveChangesAsync(ct);

                await mailService.SendBulkEmailAsync(reviewers, $"[✅ REANUDADO] {newsletter.Subject}",
                    NurturingContentRenderer.WrapInHtmlEmail(
                        "<p style=\"background:#e8f5e9;padding:10px 14px;border-left:3px solid #43a047;font-size:13px;color:#555;margin-bottom:20px;\"><b>✅ Newsletter reanudado</b><br>" +
                        $"Reactivado por: {string.Join(", ", resumeEmails.Select(e => e.From))}</p>" + newsletter.Body),
                    isHtml: true, ct: ct);

                return Ok(new { monthKey, version = newsletter.Version, action = "resumed", resumeRequestsFrom = resumeEmails.Select(e => e.From) });
            }

            // Process revisions
            if (revisionEmails.Count > 0)
            {
                var combinedFeedback = string.Join("\n\n---\n\n",
                    revisionEmails.Select(e => $"De {e.From}:\n{e.Body}"));

                logger.LogInformation("Delegating newsletter revision to Python agent");
                var agentRevision = await agentClient.ReviseNewsletterAsync(
                    newsletter.Subject, newsletter.Body, combinedFeedback, ct);
                if (agentRevision is null)
                {
                    return StatusCode(502, new
                    {
                        error = "Python agent did not respond or failed to revise newsletter.",
                        monthKey,
                        version = newsletter.Version,
                    });
                }

                var revised = agentRevision;

                newsletter.Subject = revised.Subject;
                newsletter.Body = revised.Body;
                newsletter.ReportTitle = revised.ReportTitle;
                newsletter.ExecutiveSummary = revised.ExecutiveSummary;
                newsletter.ArtifactJson = revised.ArtifactJson;
                newsletter.Version++;
                await db.SaveChangesAsync(ct);

                // Resend revised version to reviewers
                var reviewNote = $"""
                    <p style="background:#fffde7;padding:10px 14px;border-left:3px solid #f9a825;font-size:13px;color:#555;margin-bottom:20px;">
                    <b>Nota para revisores:</b> Versión <b>{newsletter.Version}</b> corregida según el feedback.
                    Se envía el <b>{cycle.SendDate:dd/MM/yyyy}</b> si no hay más correcciones.<br><br>
                    <b>⏸ Para suspender el envío</b>, respondé con <b>"NO ENVIAR"</b>.
                    </p>
                    """;
                var reviewWrapped = NurturingContentRenderer.WrapInHtmlEmail(reviewNote + revised.Body);
                await mailService.SendBulkEmailAsync(reviewers, $"[REVISIÓN v{newsletter.Version}] {revised.Subject}", reviewWrapped, isHtml: true, ct: ct);

                return Ok(new
                {
                    monthKey,
                    version = newsletter.Version,
                    action = "revised",
                    feedbackFrom = revisionEmails.Select(e => e.From),
                    newSubject = revised.Subject,
                    note = $"Newsletter revised to v{newsletter.Version} and resent to reviewers."
                });
            }

            return Ok(new { monthKey, version = newsletter.Version, action = "none", feedbackFound = feedbackEmails.Count,
                note = "Feedback found but no actionable changes were applied." });
        }
        catch (Exception ex)
        {
            logger.LogError(ex, "Trigger-check-feedback failed");
            return StatusCode(500, new { error = "Failed to check feedback.", detail = ex.Message });
        }
    }

    /// <summary>
    /// Forces sending the next pending newsletter cycle to leads, exactly like the scheduled
    /// send flow. Includes AI-personalized closings when possible.
    /// Respects the on-hold flag unless <c>?force=true</c> is passed.
    /// Use <c>?limit=N</c> to send to only N recipients (useful for testing).
    /// Use <c>?offset=N</c> to skip the first N recipients (pagination).
    /// Use <c>?dealId=N</c> to send only to the contact of a specific Pipedrive deal.
    ///
    /// <b>Production mode</b> (no limit/offset/dealId): launches the send in background
    /// and returns immediately. Use <c>GET trigger-send/status</c> to check progress.
    /// <b>Test mode</b> (with limit/offset/dealId): sends synchronously and returns results.
    /// </summary>
    [HttpPost("trigger-send")]
    public async Task<IActionResult> TriggerSend(
        [FromQuery] bool force = false,
        [FromQuery] int? limit = null,
        [FromQuery] int? offset = null,
        [FromQuery] int? dealId = null,
        CancellationToken ct = default)
    {
        if (!mailService.IsConfigured)
            return BadRequest(new { error = "Mail service (IMAP/SMTP) is not configured." });

        var options = nurturingOptions.Value;

        logger.LogInformation("Manual trigger-send requested via endpoint (force={Force})", force);

        try
        {
            var buenosAires = TimeZoneInfo.FindSystemTimeZoneById("America/Buenos_Aires");
            var now = TimeZoneInfo.ConvertTimeFromUtc(DateTime.UtcNow, buenosAires);
            var today = DateOnly.FromDateTime(now);
            var cycleResolution = await ResolveNextPendingCycleAsync(today, ct);
            if (cycleResolution is null)
                return NotFound(new { error = "No pending newsletter cycle found." });

            var (cycle, newsletter) = cycleResolution.Value;
            var monthKey = cycle.CycleKey;

            if (newsletter is null)
                return NotFound(new { error = $"No unsent newsletter found for {monthKey}." });

            if (newsletter.IsOnHold && !force)
                return Conflict(new
                {
                    error = $"Newsletter {monthKey} is ON HOLD. A reviewer must reply \"REANUDAR\" or pass ?force=true to override.",
                    monthKey,
                    version = newsletter.Version,
                    isOnHold = true
                });

            // Get recipients
            var allRecipients = await GetRecipientsAsync(options, ct);
            if (allRecipients.Count == 0)
                return BadRequest(new { error = "No recipients found (check RecipientOverride or Pipedrive nurturing stage)." });

            // Filter by dealId if provided
            if (dealId.HasValue)
            {
                allRecipients = allRecipients.Where(c => c.DealId == dealId.Value).ToList();
                if (allRecipients.Count == 0)
                {
                    // Deal not in nurturing stage — fetch it directly from Pipedrive (any stage/status)
                    var directContact = await pipedrive.GetDealContactAsync(dealId.Value, ct);
                    if (directContact is null)
                        return NotFound(new { error = $"No recipient found for dealId={dealId.Value} (not found or has no contact email)." });
                    allRecipients = [directContact];
                }
                logger.LogInformation("Filtered by dealId={DealId}: {Count} recipient(s)", dealId.Value, allRecipients.Count);
            }

            // Apply offset + limit (useful for paginated testing)
            IEnumerable<PipedriveDealContact> filtered = allRecipients;
            if (offset.HasValue && offset.Value > 0)
                filtered = filtered.Skip(offset.Value);
            if (limit.HasValue && limit.Value > 0)
                filtered = filtered.Take(limit.Value);
            var recipients = filtered.ToList();

            if (recipients.Count == 0)
                return BadRequest(new { error = $"No recipients after applying offset={offset} limit={limit}. Total available: {allRecipients.Count}." });

            var isSubset = limit.HasValue || offset.HasValue;

            // ── Sync mode: only for single-deal sends (quick, one email) ──
            if (dealId.HasValue)
            {
                logger.LogInformation("Sync mode (dealId={DealId}): sending to {Count} recipient(s)",
                    dealId.Value, recipients.Count);
                return await SendSynchronousAsync(newsletter, recipients, allRecipients.Count, options, offset, limit, dealId, ct);
            }

            // ── Background mode: fire-and-forget for bulk sends ──
            if (_activeSend is { IsComplete: false })
            {
                return Conflict(new
                {
                    error = "A background send is already in progress.",
                    monthKey = _activeSend.MonthKey,
                    sent = _activeSend.Sent,
                    total = _activeSend.TotalRecipients,
                    startedAt = _activeSend.StartedAt,
                    note = "Use GET trigger-send/status to check progress."
                });
            }

            var status = new SendStatus
            {
                MonthKey = monthKey,
                Version = newsletter.Version,
                Subject = newsletter.Subject,
                TotalRecipients = recipients.Count,
            };
            _activeSend = status;

            // Capture newsletter data before scope ends
            var newsletterSubject = newsletter.Subject;
            var newsletterBody = newsletter.Body;
            var newsletterMonthKey = newsletter.MonthKey;
            var recipientOverride = options.RecipientOverride;
            var capturedRecipients = recipients.ToList();

            logger.LogInformation("Launching background send for {MonthKey} v{Version} to {Count} recipients (subset={IsSubset})",
                monthKey, newsletter.Version, recipients.Count, isSubset);

            _ = Task.Run(() => SendInBackgroundAsync(
                newsletterSubject, newsletterBody, newsletterMonthKey, newsletter.Version,
                capturedRecipients, recipientOverride, isSubset, status));

            return Accepted(new
            {
                monthKey,
                version = newsletter.Version,
                subject = newsletter.Subject,
                totalRecipients = recipients.Count,
                totalAvailable = allRecipients.Count,
                limitApplied = limit,
                offsetApplied = offset,
                isSubset,
                startedAt = status.StartedAt,
                note = $"Background send launched for {recipients.Count} recipients{(isSubset ? $" (subset of {allRecipients.Count})" : "")}. Use GET trigger-send/status to monitor progress."
            });
        }
        catch (Exception ex)
        {
            logger.LogError(ex, "Trigger-send failed");
            return StatusCode(500, new { error = "Failed to send newsletter.", detail = ex.Message });
        }
    }

