        });
    }

    /// <summary>
    /// Synchronous send for test mode (small batches with limit/offset/dealId).
    /// </summary>
    private async Task<IActionResult> SendSynchronousAsync(
        NurturingEmailEntity newsletter,
        List<PipedriveDealContact> recipients,
        int totalRecipientsCount,
        NurturingOptions options,
        int? offset, int? limit, int? dealId,
        CancellationToken ct)
    {
        // Pre-generate AI closings
        var aiClosings = new Dictionary<string, string>();
        if (agentClient.IsConfigured && pipedrive.IsConfigured)
        {
            var processedDeals = new Dictionary<int, List<string>>();
            foreach (var contact in recipients)
            {
                if (ct.IsCancellationRequested) break;
                try
                {
                    if (!processedDeals.TryGetValue(contact.DealId, out var notes))
                    {
                        notes = await pipedrive.GetDealNotesAsync(contact.DealId, ct);
                        processedDeals[contact.DealId] = notes;
                    }
                    if (notes.Count > 0)
                    {
                        var firstName = NurturingWorkflowSupport.ExtractFirstName(contact.ContactName);
                        var aiClosing = await agentClient.GenerateClosingAsync(
                            newsletter.Subject, newsletter.Body, firstName, contact.OrganizationName, notes, ct);
                        if (aiClosing is not null)
                            aiClosings[contact.ContactEmail] = aiClosing;
                    }
                }
                catch (Exception ex)
                {
                    logger.LogWarning(ex, "Failed to generate AI closing for {Email}", contact.ContactEmail);
                }
            }
        }

        var recipientOverride = options.RecipientOverride;
        var hasOverride = !string.IsNullOrWhiteSpace(recipientOverride);
        if (hasOverride)
            logger.LogWarning("RecipientOverride active — all emails redirect to {Override}", recipientOverride);

        var sentCount = 0;
        var isFirst = true;
        foreach (var contact in recipients)
        {
            if (ct.IsCancellationRequested) break;

            if (!isFirst)
                await Task.Delay(TimeSpan.FromSeconds(2), ct);
            isFirst = false;

            var firstName = NurturingWorkflowSupport.ExtractFirstName(contact.ContactName);
            var closing = aiClosings.TryGetValue(contact.ContactEmail, out var aiClose)
                ? aiClose
                : NurturingWorkflowSupport.BuildPersonalClosing(firstName, contact.OrganizationName);
            var personalHtml = NurturingContentRenderer.WrapInHtmlEmail(newsletter.Body, firstName, closing);

            var effectiveEmail = hasOverride ? recipientOverride! : contact.ContactEmail;
            try
            {
                await mailService.SendEmailAsync(effectiveEmail, newsletter.Subject, personalHtml, isHtml: true, ct: ct);
                sentCount++;
                if (hasOverride)
                    logger.LogInformation("Sent to {Override} (as {Contact} / {Org})", effectiveEmail, contact.ContactName, contact.OrganizationName);
            }
            catch (Exception ex)
            {
                logger.LogError(ex, "Failed to send newsletter to {Email}", contact.ContactEmail);
            }
        }

        return Ok(new
        {
            monthKey = newsletter.MonthKey,
            version = newsletter.Version,
            subject = newsletter.Subject,
            sentTo = sentCount,
            totalRecipients = totalRecipientsCount,
            offsetApplied = offset,
            limitApplied = limit,
            dealIdFilter = dealId,
            redirectedTo = hasOverride ? recipientOverride : null,
            aiClosings = aiClosings.Count,
            templateClosings = recipients.Count - aiClosings.Count,
            markedAsSent = false,
            recipients = recipients.Select(c => new { c.DealId, c.ContactName, c.ContactEmail, c.OrganizationName }),
            note = $"TEST MODE: Newsletter sent to {sentCount} recipients{(hasOverride ? $" (redirected to {recipientOverride})" : "")}. Total available: {totalRecipientsCount}. NOT marked as sent."
        });
    }

    /// <summary>
    /// Background fire-and-forget send. Runs in its own DI scope with human-like delays.
    /// </summary>
    private async Task SendInBackgroundAsync(
        string newsletterSubject, string newsletterBody, string monthKey, int version,
        List<PipedriveDealContact> recipients, string? recipientOverride, bool isSubset, SendStatus status)
    {
        await using var scope = scopeFactory.CreateAsyncScope();
        var bgLogger = scope.ServiceProvider.GetRequiredService<ILogger<NurturingController>>();
        var bgMail = scope.ServiceProvider.GetRequiredService<INurturingMailService>();
        var bgPipedrive = scope.ServiceProvider.GetRequiredService<IPipedriveService>();
        var bgDb = scope.ServiceProvider.GetRequiredService<NovitDbContext>();

        var hasOverride = !string.IsNullOrWhiteSpace(recipientOverride);

        try
        {
            bgLogger.LogInformation("▶ Background send started: {MonthKey} v{Version} → {Count} recipients",
                monthKey, version, recipients.Count);

            // Pre-generate AI closings
            var aiClosings = new Dictionary<string, string>();
            if (agentClient.IsConfigured && bgPipedrive.IsConfigured)
            {
                bgLogger.LogInformation("Pre-generating AI closings for {Count} recipients…", recipients.Count);
                var processedDeals = new Dictionary<int, List<string>>();
                foreach (var contact in recipients)
                {
                    try
                    {
                        if (!processedDeals.TryGetValue(contact.DealId, out var notes))
                        {
                            notes = await bgPipedrive.GetDealNotesAsync(contact.DealId, CancellationToken.None);
                            processedDeals[contact.DealId] = notes;
                        }
                        if (notes.Count > 0)
                        {
                            var firstName = NurturingWorkflowSupport.ExtractFirstName(contact.ContactName);
                            var aiClosing = await agentClient.GenerateClosingAsync(
                                newsletterSubject, newsletterBody, firstName, contact.OrganizationName, notes, CancellationToken.None);
                            if (aiClosing is not null)
                                aiClosings[contact.ContactEmail] = aiClosing;
                        }
                    }
                    catch (Exception ex)
                    {
                        bgLogger.LogWarning(ex, "Failed to generate AI closing for {Email}", contact.ContactEmail);
                    }
                }
                status.AiClosings = aiClosings.Count;
                bgLogger.LogInformation("AI closings: {Ai}/{Total} generated, {Template} will use template",
                    aiClosings.Count, recipients.Count, recipients.Count - aiClosings.Count);
            }

            if (hasOverride)
                bgLogger.LogWarning("RecipientOverride active — all emails redirect to {Override}", recipientOverride);

            // Send emails with human-like delays
            var isFirst = true;
            foreach (var contact in recipients)
            {
                if (!isFirst)
                {
                    var delaySec = NurturingWorkflowSupport.GetHumanLikeDelay();
                    bgLogger.LogInformation("⏳ Human-like delay: {Delay}s before next send ({Sent}/{Total})",
                        delaySec, status.Sent, recipients.Count);
                    await Task.Delay(TimeSpan.FromSeconds(delaySec));
                }
                isFirst = false;

                var firstName = NurturingWorkflowSupport.ExtractFirstName(contact.ContactName);
                var closing = aiClosings.TryGetValue(contact.ContactEmail, out var aiClose)
                    ? aiClose
                    : NurturingWorkflowSupport.BuildPersonalClosing(firstName, contact.OrganizationName);
                var personalHtml = NurturingContentRenderer.WrapInHtmlEmail(newsletterBody, firstName, closing);

                var effectiveEmail = hasOverride ? recipientOverride! : contact.ContactEmail;
                try
                {
                    await bgMail.SendEmailAsync(effectiveEmail, newsletterSubject, personalHtml, isHtml: true, ct: CancellationToken.None);
                    status.Sent++;
                    bgLogger.LogInformation("✉ [{Sent}/{Total}] Sent to {Email} ({Name} / {Org})",
                        status.Sent, recipients.Count, effectiveEmail, contact.ContactName, contact.OrganizationName);
                }
                catch (Exception ex)
                {
                    status.Failed++;
                    bgLogger.LogError(ex, "✗ Failed to send to {Email}", contact.ContactEmail);
                }
            }

            // Mark as sent only if full send (no override, no subset)
            if (!hasOverride && !isSubset)
            {
                var newsletter = await bgDb.NurturingEmails
                    .FirstOrDefaultAsync(e => e.MonthKey == monthKey && !e.IsSent);
                if (newsletter is not null)
                {
                    newsletter.IsSent = true;
                    newsletter.SentAt = DateTimeOffset.UtcNow;
                    await bgDb.SaveChangesAsync();
                    status.MarkedAsSent = true;
                    bgLogger.LogInformation("✅ Newsletter {MonthKey} marked as sent", monthKey);
                }
            }
            else
            {
                bgLogger.LogWarning("Newsletter NOT marked as sent (override={Override}, subset={Subset})",
                    hasOverride, isSubset);
            }

            status.IsComplete = true;
            status.CompletedAt = DateTimeOffset.UtcNow;
            bgLogger.LogInformation("✅ Background send complete: {Sent}/{Total} sent, {Failed} failed, elapsed {Elapsed}",
                status.Sent, recipients.Count, status.Failed, status.CompletedAt - status.StartedAt);
        }
        catch (Exception ex)
        {
            status.IsComplete = true;
            status.CompletedAt = DateTimeOffset.UtcNow;
            status.Error = ex.Message;
            bgLogger.LogError(ex, "❌ Background send failed catastrophically");
        }
    }

    /// <summary>
    /// Forces a check for unanswered lead replies and auto-responds with AI.
    /// Mirrors the daily scheduled flow: reads IMAP inbox for replies from leads,
    /// generates AI responses, sends replies, and logs to Pipedrive.
    /// </summary>
    [HttpPost("trigger-check-replies")]
    public async Task<IActionResult> TriggerCheckReplies(CancellationToken ct)
    {
        if (!mailService.IsConfigured)
            return BadRequest(new { error = "Mail service (IMAP) is not configured." });

        if (!agentClient.IsConfigured)
            return BadRequest(new { error = "Python agent is not configured for nurturing replies." });

        var options = nurturingOptions.Value;

        logger.LogInformation("Manual trigger-check-replies requested via endpoint");

        try
        {
            var unanswered = await mailService.GetUnansweredRepliesAsync(30, ct);

            // Exclude reviewer validation emails
            var reviewerSet = new HashSet<string>(options.GetReviewerList(), StringComparer.OrdinalIgnoreCase);
            var leadReplies = unanswered
                .Where(e => !(reviewerSet.Contains(e.From) &&
                              e.Subject.Contains("REVISIÓN", StringComparison.OrdinalIgnoreCase)))
                .ToList();

            if (leadReplies.Count == 0)
                return Ok(new { repliesFound = 0, repliesSent = 0, note = "No unanswered lead replies found." });

            // Build email → dealId map from Pipedrive
            var dealContactMap = new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase);
            if (pipedrive.IsConfigured)
            {
                try
                {
                    var contacts = await pipedrive.GetNurturingDealContactsAsync(ct);
                    foreach (var contact in contacts)
                        dealContactMap.TryAdd(contact.ContactEmail, contact.DealId);
                }
                catch (Exception ex)
                {
                    logger.LogWarning(ex, "Failed to load Pipedrive deals for note updates");
                }
            }

            // Safety filter: only respond to known Pipedrive nurturing contacts
            if (dealContactMap.Count > 0)
            {
                var knownEmails = new HashSet<string>(dealContactMap.Keys, StringComparer.OrdinalIgnoreCase);
                foreach (var reviewer in reviewerSet) knownEmails.Add(reviewer);

                leadReplies = leadReplies.Where(e => knownEmails.Contains(e.From)).ToList();
                if (leadReplies.Count == 0)
                    return Ok(new { repliesFound = unanswered.Count, repliesSent = 0, note = "Replies found but none from known Pipedrive nurturing contacts." });
            }

            // ── SAFETY FILTER 3: Only respond to emails whose subject matches a sent newsletter ──
            // Prevents auto-replying to manual conversations with the same contacts on non-nurturing topics.
            var sentNewsletterSubjects = await db.NurturingEmails
                .Where(n => n.IsSent && !string.IsNullOrEmpty(n.Subject))
                .Select(n => n.Subject)
                .ToListAsync(ct);

            if (sentNewsletterSubjects.Count > 0)
            {
                var beforeCount = leadReplies.Count;
                leadReplies = leadReplies.Where(e => IsNurturingNewsletterReply(e.Subject, sentNewsletterSubjects)).ToList();
                logger.LogInformation("Newsletter subject filter: {Before} → {After} replies", beforeCount, leadReplies.Count);

                if (leadReplies.Count == 0)
                    return Ok(new { repliesFound = unanswered.Count, repliesSent = 0, note = "Replies found but none match sent newsletter subjects." });
            }

            // Determine effective recipient: if RecipientOverride is set, redirect all replies there (testing mode)
            var recipientOverride = options.RecipientOverride;
            var hasOverride = !string.IsNullOrWhiteSpace(recipientOverride);
            if (hasOverride)
            {
                logger.LogWarning("RecipientOverride is set — all auto-replies will be redirected to {Override} instead of real senders",
                    recipientOverride);
            }

            var results = new List<object>();
            var repliedMessageIds = new List<string>();
            foreach (var email in leadReplies)
            {
                if (ct.IsCancellationRequested) break;
                try
                {
                    var senderName = email.From.Contains('@')
                        ? email.From.Split('@')[0].Replace('.', ' ').Replace('_', ' ')
                        : email.From;

                    var reply = await agentClient.GenerateReplyAsync(email.Subject, email.Body, senderName, ct);
                    if (string.IsNullOrWhiteSpace(reply))
                        throw new InvalidOperationException("Python agent did not return a reply for the lead email.");

                    // Use override recipient if configured, otherwise reply to the actual sender
                    var effectiveRecipient = hasOverride ? recipientOverride! : email.From;
                    await mailService.SendReplyAsync(effectiveRecipient, email.Subject, reply, email.MessageId, ct: ct);

                    repliedMessageIds.Add(email.MessageId);

                    // Log to Pipedrive
                    if (dealContactMap.TryGetValue(email.From, out var dealId))
                    {
                        var noteHtml = $"<b>Respuesta de nurturing — {DateTimeOffset.UtcNow:yyyy-MM-dd}</b><br><br>" +
                                       $"<b>De:</b> {WebUtility.HtmlEncode(email.From)}<br>" +
                                       $"<b>Asunto:</b> {WebUtility.HtmlEncode(email.Subject)}<br><br>" +
                                       $"<b>Mensaje del lead:</b><br>{WebUtility.HtmlEncode(email.Body).Replace("\n", "<br>")}<br><br>" +
                                       $"<b>Respuesta automática:</b><br>{WebUtility.HtmlEncode(reply).Replace("\n", "<br>")}";
                        await pipedrive.AddNoteToDealAsync(dealId, noteHtml, ct);
                    }

                    results.Add(new { from = email.From, sentTo = effectiveRecipient, subject = email.Subject, status = "replied", redirected = hasOverride, loggedToPipedrive = dealContactMap.ContainsKey(email.From) });
                }
                catch (Exception ex)
                {
                    logger.LogError(ex, "Failed to auto-reply to {From}", email.From);
                    results.Add(new { from = email.From, subject = email.Subject, status = "failed", error = ex.Message });
                }
            }

            // Mark all successfully replied emails as read
            if (repliedMessageIds.Count > 0)
            {
                try
                {
                    await mailService.MarkAsReadAsync(repliedMessageIds, ct);
                    logger.LogInformation("Marked {Count} replied emails as read", repliedMessageIds.Count);
                }
                catch (Exception ex)
                {
                    logger.LogError(ex, "Failed to mark replied emails as read");
                }
            }

            return Ok(new
            {
                repliesFound = leadReplies.Count,
                repliesSent = results.Count(r => ((dynamic)r).status == "replied"),
                results,
                note = "Lead replies processed and auto-responded."
            });
        }
        catch (Exception ex)
        {
            logger.LogError(ex, "Trigger-check-replies failed");
            return StatusCode(500, new { error = "Failed to check replies.", detail = ex.Message });
        }
    }

