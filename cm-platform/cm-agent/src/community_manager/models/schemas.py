"""Pydantic schemas for the Community Manager agent."""

from __future__ import annotations

from datetime import datetime
from enum import Enum

from pydantic import BaseModel, Field, model_validator


FIXED_VIDEO_DURATION_SECONDS = 20
MIN_IMAGE_POST_IMAGES = 2
MAX_IMAGE_POST_IMAGES = 6


# ── Enums ──────────────────────────────────────────────────────────

class ContentType(str, Enum):
    IMAGE_POST = "image_post"
    TEXT_POST = "text_post"
    VIDEO_POST = "video_post"


class ImageModelChoice(str, Enum):
    IMAGE_1_5 = "image_1_5"
    IMAGE_2 = "image_2"


class ImageQuality(str, Enum):
    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"


class VideoTemplateChoice(str, Enum):
    STORY_EXPLAINER = "story_explainer"
    NEWS_BREAKDOWN = "news_breakdown"
    UI_WALKTHROUGH = "ui_walkthrough"
    CASE_STUDY = "case_study"
    MYTH_VS_REALITY = "myth_vs_reality"


class ReviewStage(str, Enum):
    PRE_MEDIA = "pre_media"
    FINAL = "final"


class PostStatus(str, Enum):
    PLANNED = "planned"
    DRAFT = "draft"
    EVALUATED = "evaluated"
    APPROVED = "approved"
    PUBLISHED = "published"
    REJECTED = "rejected"


class ContentTone(str, Enum):
    PROFESSIONAL = "professional"
    CASUAL = "casual"
    INSPIRATIONAL = "inspirational"
    EDUCATIONAL = "educational"
    PROMOTIONAL = "promotional"


class Platform(str, Enum):
    INSTAGRAM = "instagram"
    FACEBOOK = "facebook"
    TIKTOK = "tiktok"


class ReplyTargetType(str, Enum):
    DIRECT_MESSAGE = "direct_message"
    COMMENT = "comment"


# ── Strategist output ─────────────────────────────────────────────

class ContentStrategy(BaseModel):
    """Output of the Strategist node."""
    content_type: ContentType
    topic: str
    angle: str = ""
    objective: str
    target_audience: str = "General followers"
    tone: ContentTone = ContentTone.PROFESSIONAL
    key_messages: list[str] = Field(default_factory=list)
    supporting_points: list[str] = Field(default_factory=list)
    language: str = "es-AR"
    image_model: ImageModelChoice = ImageModelChoice.IMAGE_2
    image_quality: ImageQuality = ImageQuality.HIGH
    video_duration_seconds: int = Field(default=FIXED_VIDEO_DURATION_SECONDS, ge=4, le=30)
    num_images: int = Field(default=MIN_IMAGE_POST_IMAGES, ge=0)
    video_template: VideoTemplateChoice = VideoTemplateChoice.STORY_EXPLAINER
    reasoning: str = ""

    @model_validator(mode="after")
    def lock_video_duration(self):
        self.num_images = max(0, min(self.num_images, MAX_IMAGE_POST_IMAGES))
        if self.content_type == ContentType.VIDEO_POST:
            self.video_duration_seconds = FIXED_VIDEO_DURATION_SECONDS
        if self.content_type == ContentType.IMAGE_POST:
            self.num_images = max(self.num_images, MIN_IMAGE_POST_IMAGES)
        return self


