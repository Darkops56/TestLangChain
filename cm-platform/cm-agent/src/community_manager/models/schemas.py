class RadarChartItem(BaseModel):
    """A quantitative datapoint rendered in the highlighted chart."""
    label: str
    value: float
    unit: str
    source_title: str
    source_url: str


class BenchmarkEntry(BaseModel):
    """A single model in the top 5 benchmark + pricing ranking (Slide 1 tables).

    ``benchmark_name`` lets each entry cite the specific benchmark the
    score comes from. The snapshot's top-level ``BenchmarkSnapshot.benchmark_name``
    is the *preferred* benchmark (typically MMLU Pro). If a model's MMLU
    Pro score isn't public, the researcher can use GPQA Diamond, AIME
    2025, SWE-bench Verified, MATH-500, etc. as a fallback — the
    benchmark_name per entry makes the substitution transparent in the
    slide.
    """
    vendor: str = ""            # "OpenAI", "Anthropic", "Google DeepMind", "Meta", "Mistral", "DeepSeek", "Qwen", "xAI"
    model: str = ""             # "GPT-5.4", "Claude Opus 4.8", "Gemini 3.5 Flash"
    benchmark_name: str = "MMLU Pro"  # which benchmark the `score` field is on
    score: float | None = None  # benchmark score (0-100). None if not found.
    cost_per_1m_input: float | None = None   # USD per 1M input tokens
    cost_per_1m_output: float | None = None  # USD per 1M output tokens
    rank: int = 0               # 1..5 (1 = best by score in benchmark top 5)


class BenchmarkSnapshot(BaseModel):
    """Top-5 benchmark + pricing snapshot for a given month (Slide 1 charts).

    The snapshot is sorted by `score` desc within `entries`. MoM deltas are
    computed downstream by the publisher from a previous-month snapshot.

    ``source`` documents where the data came from (e.g. "artificialanalysis.io"
    for research-found data, "Precios referenciales — documentación oficial
    de cada vendor" for the fallback seed). Displayed below the charts so
    the reader can verify.
    """
    benchmark_name: str = "MMLU Pro"  # default; configurable via env var
    month_key: str = ""               # "2026-06" (set by researcher at extraction time)
    entries: list[BenchmarkEntry] = Field(default_factory=list)  # max 5
    source: str = ""                  # provenance shown below charts on slide 1


class RadarReport(BaseModel):
    """Structured AI Radar payload used to build email and Google Slides artifacts."""
    subject: str
    report_title: str
    executive_summary: str  # full version for email
    slide_summary: str = ""  # short version for slide 1 (3 bullets, max 400 chars)
    insights: list[RadarInsight] = Field(default_factory=list)  # principales (hasta 3)
    insights_secondary: list[RadarInsight] = Field(default_factory=list)  # secundarios (hasta 3)
    chart_title: str = ""
    chart_subtitle: str = ""
    chart_items: list[RadarChartItem] = Field(default_factory=list)
    discarded_insights: list[dict] = Field(default_factory=list)  # descartados con score y motivo
    conclusions: str = ""  # conclusiones especulativas para slide 4
    # Slide 2 & 3: full Markdown text generated by the writer (single textbox per slide)
    slide_2_text: str = ""  # Markdown completo para Slide AR (max 500 chars)
    slide_3_text: str = ""  # Markdown completo para Slide ES (max 500 chars)
    # Slide 1 indicator boxes (legacy string format, kept for backward compat)
    benchmark_data: str = ""  # benchmark scores of top models
    adoption_data: str = ""   # AI adoption rates (Global, ES, AR)
    pricing_data: str = ""    # cost per token of main models
    # Slide 1 ranking tables (PR B): structured top 5 benchmark + pricing
    benchmark_snapshot: BenchmarkSnapshot | None = None


