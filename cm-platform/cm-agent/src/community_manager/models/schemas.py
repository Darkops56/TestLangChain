# ── Designer output ────────────────────────────────────────────────

class GeneratedImage(BaseModel):
    """A single generated image."""
    prompt: str = ""
    review_summary: str = ""
    visible_text: str = ""
    slide_number: int | None = None
    local_path: str | None = None
    url: str | None = None
    blob_name: str | None = None


class PlannedVideoClip(BaseModel):
    """A single planned supporting clip inside a composite video."""
    prompt: str = ""
    purpose: str = ""
    review_summary: str = ""
    start_second: float = 0
    duration_seconds: int = 4
    transition: str = "dissolve"


class GeneratedVideo(BaseModel):
    """A generated video."""
    prompt: str = ""
    review_summary: str = ""
    avatar_script: str = ""
    supporting_clips: list[PlannedVideoClip] = Field(default_factory=list)
    avatar_intro_seconds: int = 0
    avatar_outro_seconds: int = 0
    video_template: str = VideoTemplateChoice.STORY_EXPLAINER.value
    duration_seconds: int = FIXED_VIDEO_DURATION_SECONDS
    local_path: str | None = None
    url: str | None = None
    blob_name: str | None = None
    job_id: str | None = None


class DesignerOutput(BaseModel):
    """Output of the Designer node."""
    images: list[GeneratedImage] = Field(default_factory=list)
    video: GeneratedVideo | None = None
    style_notes: str = ""


# ── Evaluator output ──────────────────────────────────────────────

class SlideReview(BaseModel):
    """Review feedback scoped to a specific carousel slide."""
    slide_number: int = Field(ge=1, le=MAX_IMAGE_POST_IMAGES)
    approved: bool = False
    feedback: str = ""
    issues: list[str] = Field(default_factory=list)


class PromptReviewResult(BaseModel):
    """Prompt-only QA result before paying for image generation."""
    approved: bool = False
    feedback: str = ""
    issues: list[str] = Field(default_factory=list)
    slide_reviews: list[SlideReview] = Field(default_factory=list)

class EvaluationResult(BaseModel):
    """Output of the Evaluator node."""
    approved: bool = False
    score: int = Field(default=0, ge=0, le=10)
    feedback: str = ""
    issues: list[str] = Field(default_factory=list)
    slide_reviews: list[SlideReview] = Field(default_factory=list)
    retry_target: str | None = None  # "copywriter" | "designer" | "abort" | None


# ── Publisher output ──────────────────────────────────────────────

class PlatformResult(BaseModel):
    """Result from publishing to a single platform."""
    platform: Platform
    success: bool = False
    post_id: str | None = None
    error: str | None = None
    permalink: str | None = None


class PublishResult(BaseModel):
    """Aggregated result from all platforms."""
    results: list[PlatformResult] = Field(default_factory=list)
    published_at: datetime | None = None

    @property
    def all_success(self) -> bool:
        return all(r.success for r in self.results) and len(self.results) > 0


